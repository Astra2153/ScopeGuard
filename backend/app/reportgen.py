import unicodedata

from sqlalchemy import select
from sqlalchemy.orm import Session as DbSession

from app.models import Engagement, Finding, Target, User
from app.targets import is_verified_fresh

SEVERITIES = ["critical", "high", "medium", "low", "info"]
STATUSES = ["open", "not_fixed", "partially_fixed", "fixed"]
MAX_FINDINGS = 1000
_SPECIAL = set("\\`*_{}[]()<>#+!|~&")


def clean(value: str) -> str:
    """Drop control, format (for example right-to-left override), surrogate and unassigned characters."""
    return "".join(
        ch
        for ch in value
        if ch in "\n\r\t" or unicodedata.category(ch) not in ("Cc", "Cf", "Cs", "Co", "Cn")
    )


def _esc(text: str) -> str:
    return "".join("\\" + c if c in _SPECIAL else c for c in text)


def md_escape(value: str, limit: int = 300) -> str:
    """Untrusted text that must stay on one line: collapse all whitespace, then escape Markdown."""
    return _esc(" ".join(clean(value).split())[:limit])


def md_block(value: str, limit: int = 4000) -> str:
    """Untrusted multi-line text as a block quote, every line escaped and prefixed."""
    text = clean(value)[:limit].replace("\r\n", "\n").replace("\r", "\n")
    return "\n".join(("> " + _esc(line.replace("\t", " "))).rstrip() for line in text.split("\n"))


def build_report(db: DbSession, engagement: Engagement, user: User, report_id, now) -> str:
    targets = list(
        db.scalars(
            select(Target).where(Target.engagement_id == engagement.id).order_by(Target.created_at)
        )
    )
    findings = list(
        db.scalars(
            select(Finding)
            .where(Finding.engagement_id == engagement.id)
            .order_by(Finding.created_at)
            .limit(MAX_FINDINGS)
        )
    )
    rank = {s: i for i, s in enumerate(SEVERITIES)}
    findings.sort(key=lambda f: (rank.get(f.severity, 99), f.title.lower(), str(f.id)))

    lines = [
        "# Security Assessment Report",
        "",
        f"- **Engagement:** {md_escape(engagement.name, 200)}",
        f"- **Engagement ID:** {engagement.id}",
        f"- **Report ID:** {report_id}",
        f"- **Generated (UTC):** {now.isoformat()}",
        f"- **Generated by user ID:** {user.id}",
        "",
        "## Scope",
        "",
    ]
    if targets:
        lines += ["| Target | Ownership verified |", "| --- | --- |"]
        for t in targets:
            if is_verified_fresh(t):
                proof = f"yes ({t.verified_at.date().isoformat()})"
            else:
                proof = "no or expired"
            lines.append(f"| {md_escape(t.base_url, 200)} | {proof} |")
    else:
        lines.append("No targets were registered for this engagement.")

    lines += ["", "## Summary", "", "| Severity | Total | Unresolved |", "| --- | --- | --- |"]
    for sev in SEVERITIES:
        group = [f for f in findings if f.severity == sev]
        unresolved = sum(1 for f in group if f.status != "fixed")
        lines.append(f"| {sev} | {len(group)} | {unresolved} |")
    lines += ["", "| Status | Count |", "| --- | --- |"]
    for status in STATUSES:
        lines.append(f"| {status} | {sum(1 for f in findings if f.status == status)} |")

    lines += ["", "## Findings", ""]
    if not findings:
        lines += ["No findings were recorded.", ""]
    for n, f in enumerate(findings, start=1):
        lines += [
            f"### {n}. [{f.severity.upper()}] {md_escape(f.title)}",
            "",
            f"- **Status:** {f.status}",
            f"- **Source:** {f.source}",
            f"- **Finding ID:** {f.id}",
            "",
        ]
        if f.description.strip():
            lines += [md_block(f.description), ""]
    if len(findings) == MAX_FINDINGS:
        lines += [f"Only the first {MAX_FINDINGS} findings are shown.", ""]

    lines += [
        "## Method and limits",
        "",
        "Findings marked scanner come from non-intrusive configuration checks. Findings marked authz "
        "come from a two-identity object-level authorization comparison. Neither is a full "
        "penetration test, and an issue that is not listed has not been shown to be absent.",
        "",
        "A finding is closed only when a person marks it as fixed. A later scan that still sees the "
        "issue reopens it.",
        "",
        "This document is signed. Verify it with the ScopeGuard public key before relying on it.",
        "",
    ]
    return "\n".join(lines)
